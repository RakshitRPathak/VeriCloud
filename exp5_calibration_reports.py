"""E5: calibration, selective prediction (risk-coverage) and sample source-validated reports."""
from common import *
import pickle, time, pandas as pd
from vericloud import *
from vericloud.benchmark import run_methods, split_masks
from vericloud.pipeline import VeriCloud
from vericloud.metrics import reliability_curve, risk_coverage, ece
from vericloud.report import build_report, to_markdown, verify_text

SET = "Under attack (30% of claims targeted, 10 sybil articles each)"
METHODS = ["Majority vote", "Truth discovery (EM, no independence)", "Credibility prior (no learning)", "VeriCloud", "Oracle reliability"]

if __name__ == "__main__":
    runs = [r for r in pickle.load(open(RES / "_e1_pooled.pkl", "rb")) if r["setting"] == SET]
    style(); fig, ax = plt.subplots(1, 3, figsize=(14, 4))
    stats_out = {}
    for m in METHODS:
        P = np.concatenate([r["pooled"][m]["P"] for r in runs]); y = np.concatenate([r["y"] for r in runs])
        S = np.concatenate([r["pooled"][m]["S"] for r in runs]); mm = np.concatenate([r["pooled"][m]["m"] for r in runs])
        cov = y != NEI; Pc = P[cov]; yc = (y[cov] == SUPPORTED).astype(int)
        x_, y_, n_ = reliability_curve(Pc, yc)
        if m in ("VeriCloud", "Majority vote", "Truth discovery (EM, no independence)"):
            ax[0].plot(x_, y_, marker="o", ms=4, color=PAL[m], label=f"{m} (ECE {ece(Pc, yc):.3f})")
        conf = np.abs(Pc - .5) * (mm[cov] >= 0.5)
        correct = ((Pc >= .5).astype(int) == yc)
        c_, r_, aurc = risk_coverage(conf + 1e-9 * np.random.default_rng(0).random(len(conf)), correct)
        ax[1].plot(c_, r_, color=PAL[m], lw=2.2 if m == "VeriCloud" else 1.4, ls="--" if "Oracle" in m else "-", label=f"{m} (AURC {aurc:.3f})")
        stats_out[m] = dict(ece=ece(Pc, yc), aurc=aurc, risk_at_50pct_coverage=float(r_[int(.5 * len(r_))]), risk_at_80pct_coverage=float(r_[int(.8 * len(r_))]))
    ax[0].plot([0, 1], [0, 1], ":", color="#555"); ax[0].set_xlabel("predicted P(claim true)"); ax[0].set_ylabel("empirical frequency"); ax[0].set_title("Reliability diagram (covered claims)"); ax[0].legend(fontsize=7)
    ax[1].set_xlabel("coverage (fraction answered)"); ax[1].set_ylabel("error rate on answered claims"); ax[1].set_title("Selective verification (risk-coverage)"); ax[1].legend(fontsize=7)
    # abstention behaviour: where does VeriCloud abstain?
    P = np.concatenate([r["pooled"]["VeriCloud"]["pred"] for r in runs]); y = np.concatenate([r["y"] for r in runs])
    cm = np.array([[np.mean(P[y == a] == b) for b in range(3)] for a in range(3)])
    im = ax[2].imshow(cm, cmap="Reds", vmin=0, vmax=1); ax[2].grid(False)
    ax[2].set_xticks(range(3)); ax[2].set_yticks(range(3)); ax[2].set_xticklabels(["SUPP", "REF", "NEI"]); ax[2].set_yticklabels(["SUPP", "REF", "NEI"])
    ax[2].set_xlabel("VeriCloud verdict"); ax[2].set_ylabel("true label"); ax[2].set_title("Confusion (row-normalised)")
    for i in range(3):
        for j in range(3): ax[2].text(j, i, f"{cm[i,j]:.2f}", ha="center", va="center", color="white" if cm[i, j] > .5 else "black")
    savefig("e5_calibration_selective"); save_json("e5_calibration_selective.json", dict(stats=stats_out, confusion=cm))
    print(pd.DataFrame(stats_out).T.round(3).to_string()); print(cm.round(3))

    # ---------- sample reports (first example of each category in claim order; not cherry-picked)
    st, pr = models()
    w = generate_world(WorldConfig(seed=600, labeled_frac=0.2, campaign_share=0.3, campaign_strength=10))
    nc = VeriCloud(w, stance=st, prior_model=pr); tab = nc.build_table(); claims = w.claims; masks = split_masks(claims)
    nc.learn_sources(tab, claims, np.array([c.verified for c in claims]) & masks[0]); nc.calibrate(tab, claims, masks[1])
    pred = nc.predict(tab, claims, mc=200); test = np.flatnonzero(masks[2])
    cats = {"correct_supported": lambda i: claims[i].label == 0 and pred["pred"][i] == 0,
            "correct_refuted": lambda i: claims[i].label == 1 and pred["pred"][i] == 1 and not claims[i].targeted,
            "correct_not_enough_info": lambda i: claims[i].label == 2 and pred["pred"][i] == 2,
            "attacked_claim_defended": lambda i: claims[i].targeted and claims[i].label == pred["pred"][i] and pred["flip"][i] < .5,
            "wrong_verdict": lambda i: claims[i].label != pred["pred"][i] and pred["pred"][i] != 2}
    idx = ["# Sample verification reports", "", "Generated by `experiments/exp5_calibration_reports.py` on a simulated world (seed 600, 30% of claims under sybil attack).",
           "Each is the **first test-split claim, in time order, that fits its category** (no cherry-picking). The true label is shown only for evaluation.", ""]
    for name, fn in cats.items():
        i = next((int(i) for i in test if fn(i)), None)
        if i is None: continue
        rep = build_report(nc, tab, claims, i, pred); rep["_true_label"] = VERDICTS[claims[i].label]
        (RES / "sample_reports" / f"{name}.json").write_text(json.dumps(rep, indent=2))
        md = to_markdown(rep) + f"\n_Ground truth (evaluation only): **{VERDICTS[claims[i].label]}**_\n"
        (RES / "sample_reports" / f"{name}.md").write_text(md)
        idx += [f"## {name.replace('_', ' ')}", "", md, "---", ""]
    (RES / "sample_reports" / "00_index.md").write_text("\n".join(idx))
    print("reports written:", sorted(p.name for p in (RES / "sample_reports").iterdir()))
    ok = np.mean([pred["pred"][i] == claims[i].label for i in test]); print("report-world test accuracy", round(float(ok), 3))
